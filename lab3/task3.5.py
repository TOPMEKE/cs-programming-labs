s = input()
print(f"Длина: {len(s)}")
print(f"Только буквы: {s.isalpha()}") #проверка на толкко буквы
print(f"Только цифры: {s.isdigit()}") # проверка на только цифры
print(f"Буквенно-цифровая: {s.isalnum()}")#проверка состоит ли только из букв и цифр
print(f"Содержит дефис: {'-' in s}")   # и так понятно
